// Window strides (used by src_pkt to read from the shared-memory window).
// Window layout: row i at window + i * CONV_SRC_STRIDE_1 * CONV_SRC_PACKET_SIZE.
// A window holds ceil_div(16384, 16 * pkt_size) - % block packets per row.
// CONV_SRC_STRIDE_1 = number of window-packets per row (compile-time).
#define CONV_SRC_STRIDE_1     ((16384u / (16u * SEISMIC_ELEMENT_SG_PACKET_SIZE) >= \
                                (SEISMIC_ELEMENT_SG_LOGICAL_GROUP >= 64u ? 1u : 64u / SEISMIC_ELEMENT_SG_LOGICAL_GROUP)) \
                               ? (16384u / (16u * SEISMIC_ELEMENT_SG_PACKET_SIZE) - \
                                  16384u / (16u * SEISMIC_ELEMENT_SG_PACKET_SIZE) % \
                                  (SEISMIC_ELEMENT_SG_LOGICAL_GROUP >= 64u ? 1u : 64u / SEISMIC_ELEMENT_SG_LOGICAL_GROUP)) \
                               : (SEISMIC_ELEMENT_SG_LOGICAL_GROUP >= 64u ? 1u : 64u / SEISMIC_ELEMENT_SG_LOGICAL_GROUP))
